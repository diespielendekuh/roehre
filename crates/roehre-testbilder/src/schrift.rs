//! Eine eigene 5×7-Pixelschrift für Testbilder (selbst gezeichnet, gleiche Lizenz wie roehre).

/// Glyphe als 7 Zeilen zu je 5 Bit (höchstes Bit links).
fn glyphe(c: char) -> [u8; 7] {
    let z = |s: [&str; 7]| {
        let mut g = [0u8; 7];
        for (i, zeile) in s.iter().enumerate() {
            for (j, ch) in zeile.chars().enumerate() {
                if ch == '#' {
                    g[i] |= 1 << (4 - j);
                }
            }
        }
        g
    };
    match c.to_ascii_uppercase() {
        'A' => z([".###.", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"]),
        'B' => z(["####.", "#...#", "#...#", "####.", "#...#", "#...#", "####."]),
        'C' => z([".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."]),
        'D' => z(["####.", "#...#", "#...#", "#...#", "#...#", "#...#", "####."]),
        'E' => z(["#####", "#....", "#....", "####.", "#....", "#....", "#####"]),
        'F' => z(["#####", "#....", "#....", "####.", "#....", "#....", "#...."]),
        'G' => z([".###.", "#...#", "#....", "#.###", "#...#", "#...#", ".####"]),
        'H' => z(["#...#", "#...#", "#...#", "#####", "#...#", "#...#", "#...#"]),
        'I' => z([".###.", "..#..", "..#..", "..#..", "..#..", "..#..", ".###."]),
        'J' => z(["..###", "...#.", "...#.", "...#.", "#..#.", "#..#.", ".##.."]),
        'K' => z(["#...#", "#..#.", "#.#..", "##...", "#.#..", "#..#.", "#...#"]),
        'L' => z(["#....", "#....", "#....", "#....", "#....", "#....", "#####"]),
        'M' => z(["#...#", "##.##", "#.#.#", "#.#.#", "#...#", "#...#", "#...#"]),
        'N' => z(["#...#", "##..#", "#.#.#", "#..##", "#...#", "#...#", "#...#"]),
        'O' => z([".###.", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."]),
        'P' => z(["####.", "#...#", "#...#", "####.", "#....", "#....", "#...."]),
        'Q' => z([".###.", "#...#", "#...#", "#...#", "#.#.#", "#..#.", ".##.#"]),
        'R' => z(["####.", "#...#", "#...#", "####.", "#.#..", "#..#.", "#...#"]),
        'S' => z([".####", "#....", "#....", ".###.", "....#", "....#", "####."]),
        'T' => z(["#####", "..#..", "..#..", "..#..", "..#..", "..#..", "..#.."]),
        'U' => z(["#...#", "#...#", "#...#", "#...#", "#...#", "#...#", ".###."]),
        'V' => z(["#...#", "#...#", "#...#", "#...#", "#...#", ".#.#.", "..#.."]),
        'W' => z(["#...#", "#...#", "#...#", "#.#.#", "#.#.#", "#.#.#", ".#.#."]),
        'X' => z(["#...#", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "#...#"]),
        'Y' => z(["#...#", "#...#", ".#.#.", "..#..", "..#..", "..#..", "..#.."]),
        'Z' => z(["#####", "....#", "...#.", "..#..", ".#...", "#....", "#####"]),
        'Ä' => z(["#...#", ".###.", "#...#", "#####", "#...#", "#...#", "#...#"]),
        'Ö' => z(["#...#", ".###.", "#...#", "#...#", "#...#", "#...#", ".###."]),
        'Ü' => z(["#...#", ".....", "#...#", "#...#", "#...#", "#...#", ".###."]),
        '0' => z([".###.", "#...#", "#..##", "#.#.#", "##..#", "#...#", ".###."]),
        '1' => z(["..#..", ".##..", "..#..", "..#..", "..#..", "..#..", ".###."]),
        '2' => z([".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"]),
        '3' => z(["#####", "...#.", "..#..", "...#.", "....#", "#...#", ".###."]),
        '4' => z(["...#.", "..##.", ".#.#.", "#..#.", "#####", "...#.", "...#."]),
        '5' => z(["#####", "#....", "####.", "....#", "....#", "#...#", ".###."]),
        '6' => z(["..##.", ".#...", "#....", "####.", "#...#", "#...#", ".###."]),
        '7' => z(["#####", "....#", "...#.", "..#..", ".#...", ".#...", ".#..."]),
        '8' => z([".###.", "#...#", "#...#", ".###.", "#...#", "#...#", ".###."]),
        '9' => z([".###.", "#...#", "#...#", ".####", "....#", "...#.", ".##.."]),
        ':' => z([".....", "..#..", "..#..", ".....", "..#..", "..#..", "....."]),
        '.' => z([".....", ".....", ".....", ".....", ".....", ".##..", ".##.."]),
        ',' => z([".....", ".....", ".....", ".....", ".##..", "..#..", ".#..."]),
        '-' => z([".....", ".....", ".....", "#####", ".....", ".....", "....."]),
        '/' => z([".....", "....#", "...#.", "..#..", ".#...", "#....", "....."]),
        '×' => z([".....", "#...#", ".#.#.", "..#..", ".#.#.", "#...#", "....."]),
        '!' => z(["..#..", "..#..", "..#..", "..#..", "..#..", ".....", "..#.."]),
        '?' => z([".###.", "#...#", "....#", "...#.", "..#..", ".....", "..#.."]),
        _ => [0; 7],
    }
}

/// Zeichnet Text mit Vergrößerung `groesse` (1 = 5×7 Pixel je Zeichen, 6 Pixel Vorschub).
pub fn text(bild: &mut crate::Bild, x: i32, y: i32, groesse: i32, farbe: [u8; 3], s: &str) {
    let mut cx = x;
    for c in s.chars() {
        let g = glyphe(c);
        for (zy, bits) in g.iter().enumerate() {
            for zx in 0..5 {
                if bits & (1 << (4 - zx)) != 0 {
                    bild.rechteck(cx + zx * groesse, y + zy as i32 * groesse, groesse, groesse, farbe);
                }
            }
        }
        cx += 6 * groesse;
    }
}

/// Breite eines Textes in Pixeln.
pub fn breite(s: &str, groesse: i32) -> i32 {
    s.chars().count() as i32 * 6 * groesse - groesse
}
